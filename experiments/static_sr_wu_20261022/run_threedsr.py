"""Run four true diffusion/shared-Wu feedback rounds after LR training.

The diffusion worker is a separate process. Wu model AND optimizer state are
checkpointed between rounds so its GPU allocation can be released during the
teacher step. LR Adam is reset exactly once at the start of round 0.
"""
from __future__ import annotations
import argparse
import gc
import json
import os
import random
import shutil
import socket
import subprocess
import sys
import time
import traceback
from pathlib import Path
from common import checked, identity, read, resolve, training_manifest, write_new, validate_records_bundle, validate_lr_parent_payload


def validate_teacher_receipt(receipt, input_records, expected_models, round_index, rendered_paths=None):
    """Bind this round to generated bytes, loaded weights, and exact feedback.

    The worker emits weight_loads[{checkpoint,sha256,...}] and one records entry
    per key with source LR, feedback-render, and target hashes. The driver must
    verify those producer hashes before creating priors; newly hashing arbitrary
    paths alone would accept replaced targets or a different frozen teacher.
    Returns already-validated image identities without substituting a new hash.
    """
    from methods.threedsr import UPSTREAM_COMMIT
    if receipt.get('status') != 'diffusion_round_complete' or receipt.get('round_index') != round_index:
        raise ValueError('Incomplete or wrong-round diffusion receipt')
    if receipt.get('upstream_commit') != UPSTREAM_COMMIT:
        raise ValueError('Diffusion receipt uses an unreviewed author revision')
    expected_weights = {str(resolve(item['path'])): item['sha256'] for item in expected_models}
    loaded = receipt.get('weight_loads', [])
    actual_weights = {str(resolve(item['checkpoint'])): item['sha256'] for item in loaded}
    if len(expected_weights) != 2 or len(loaded) != 2 or len(actual_weights) != 2 or actual_weights != expected_weights:
        raise ValueError('Diffusion receipt does not match the actual StableSR-Turbo and VQGAN checkpoint identities')
    expected = {item['key']: item for item in input_records}
    if len(expected) != len(input_records):
        raise ValueError('Duplicate source teacher keys')
    targets = receipt.get('targets', {})
    output_records = receipt.get('records', [])
    actual = {item['key']: item for item in output_records}
    if len(actual) != len(output_records) or set(actual) != set(expected) or set(targets) != set(expected):
        raise ValueError('Diffusion target identities are missing, duplicated, or held out')
    if round_index:
        if rendered_paths is None or set(rendered_paths) != set(expected):
            raise ValueError('Complete preceding-round shared-Wu render feedback is required')
    elif rendered_paths is not None:
        raise ValueError('The first diffusion round must not claim previous Wu feedback')
    verified = {}
    for key, source in expected.items():
        result = actual[key]
        if any(result.get(field) != source[field] for field in ('scene', 'camera', 'time', 'lr_sha256')):
            raise ValueError(f'Diffusion receipt source observation mismatch: {key}')
        generated_hash = result.get('target_sha256')
        if not isinstance(generated_hash, str) or len(generated_hash) != 64:
            raise ValueError(f'Diffusion target lacks its generation-time SHA256: {key}')
        target_path = checked({'path': targets[key], 'sha256': generated_hash})
        if round_index:
            render_hash = result.get('render_sha256')
            if not isinstance(render_hash, str) or len(render_hash) != 64:
                raise ValueError(f'Diffusion feedback lacks SHA256: {key}')
            checked({'path': rendered_paths[key], 'sha256': render_hash})
        elif result.get('render_sha256') is not None:
            raise ValueError(f'Unexpected first-round feedback: {key}')
        verified[key] = {'path': str(target_path), 'sha256': generated_hash}
    return verified


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--config',required=True);p.add_argument('--records',required=True)
    p.add_argument('--lr-checkpoint',required=True);p.add_argument('--upstream',required=True)
    p.add_argument('--stable-checkpoint',required=True);p.add_argument('--vqgan-checkpoint',required=True)
    p.add_argument('--teacher-python',default=sys.executable);p.add_argument('--out',required=True)
    p.add_argument('--runtime-assets',help='Verified OpenCLIP/VGG16/LPIPS cache registration JSON')
    p.add_argument('--wiring-fixture-steps',type=int)
    a=p.parse_args();cfg=read(a.config)
    if cfg['method']!='threedsr':raise ValueError('3DSR configuration required')
    m,rows=training_manifest(checked(cfg['manifest']),verify_pixels=True)
    records=read(a.records)
    validate_records_bundle(records,cfg['manifest'],m,rows)
    keys={f"{r['camera_id']}/{r['frame_index']:04d}":r for r in rows}
    if {r['key'] for r in records['records']}!=set(keys):raise ValueError('Teacher keys mismatch')
    for path in (a.lr_checkpoint,a.stable_checkpoint,a.vqgan_checkpoint):identity(path)
    visible=os.environ.get('CUDA_VISIBLE_DEVICES','')
    if not visible or ',' in visible or visible=='-1':raise ValueError('Exactly one admitted GPU required')
    steps=5000 if a.wiring_fixture_steps is None else a.wiring_fixture_steps
    if not 1<=steps<=5000:raise ValueError('Invalid wiring fixture length')
    teacher_python=shutil.which(a.teacher_python)
    if teacher_python is None:raise FileNotFoundError(f'Teacher Python not found: {a.teacher_python}')
    # Preserve a venv launcher: realpath can select its base interpreter.
    teacher_python=str(Path(teacher_python).absolute())
    out=resolve(a.out);out.mkdir(parents=True,exist_ok=False)
    record=dict(config=identity(a.config),source_records=identity(a.records),lr_parent=identity(a.lr_checkpoint),
        stable_checkpoint=identity(a.stable_checkpoint),vqgan_checkpoint=identity(a.vqgan_checkpoint),
        status='running',rounds=[],wiring_fixture=bool(a.wiring_fixture_steps))
    if a.runtime_assets:
        record['runtime_assets']=identity(a.runtime_assets)
    write_new(out/'run.json',record)
    previous_checkpoint=identity(a.lr_checkpoint);feedback=None
    try:
        import numpy as np
        import torch
        from backend import WuBackend
        from train_stage import optimize
        from render_eval import render_training, evaluate
        parent_payload=torch.load(checked(previous_checkpoint),map_location='cpu',weights_only=False)
        validate_lr_parent_payload(parent_payload,'threedsr')
        del parent_payload
        torch.set_num_threads(4)
        torch.backends.cuda.matmul.allow_tf32=False;torch.backends.cudnn.allow_tf32=False
        # The author seeds Python once before the four denoising/reconstruction
        # rounds. Each round resets its camera pool, but continues this RNG.
        sampling_rng=random.Random(cfg['seed'])
        record['sampling_rng_policy']='single Python Random seeded once; fresh camera pool each round; checkpointed start/end state'
        record['training_rng_policy']='seed Python/NumPy/Torch/CUDA once after first SR backend setup; restore prior training-end state after later backend reconstruction'
        training_rng=None
        for round_index in range(4):
            teacher=out/f'teacher_{round_index}'
            cmd=[teacher_python,str(Path(__file__).resolve().parent/'methods/threedsr.py'),
                '--manifest',str(resolve(a.records)),'--upstream',str(resolve(a.upstream)),
                '--stable-checkpoint',str(resolve(a.stable_checkpoint)),
                '--vqgan-checkpoint',str(resolve(a.vqgan_checkpoint)),
                '--state-root',str(out/'latents'),'--output',str(teacher),'--round-index',str(round_index)]
            if feedback:cmd+=['--rendered-paths',str(feedback)]
            worker_options={}
            runtime=None
            if a.runtime_assets:
                from methods.threedsr import prepare_runtime_assets
                runtime,environment=prepare_runtime_assets(checked(record['runtime_assets']),resolve(a.upstream),
                    out/(teacher.name+'_runtime'))
                cmd+=['--runtime-assets',str(checked(record['runtime_assets']))]
                worker_options={'cwd':runtime['execution_workdir'],'env':environment}
            teacher_started=time.perf_counter()
            subprocess.run(cmd,check=True,**worker_options)  # Completion event, no polling; failures stop the chain.
            teacher_seconds=time.perf_counter()-teacher_started
            tr=read(teacher/'receipt.json')
            if runtime is not None and tr.get('runtime_assets')!={
                    'registration':runtime['runtime_assets_identity'],
                    'execution_workdir':runtime['execution_workdir'],'offline_cache':True}:
                raise ValueError('Teacher runtime cache receipt does not match the registered assets/workdir')
            verified_targets=validate_teacher_receipt(tr,records['records'],
                [record['stable_checkpoint'],record['vqgan_checkpoint']],round_index,
                read(feedback) if feedback else None)
            priors={ (r['camera_id'],r['frame_index']):dict(sr=verified_targets[k]) for k,r in keys.items() }
            backend=WuBackend(cfg,checkpoint=previous_checkpoint)
            if round_index==0:
                backend.g.training_setup(backend.opt)  # Author loads LR geometry, not LR Adam.
                # Match the author's new SR seed, not the LR parent's RNG.
                # torch.manual_seed seeds CPU and all visible CUDA generators.
                random.seed(cfg['seed']);np.random.seed(cfg['seed']);torch.manual_seed(cfg['seed'])
                record['hardware']=dict(hostname=socket.gethostname(),CUDA_VISIBLE_DEVICES=visible,
                    torch_version=torch.__version__,gpu_name=torch.cuda.get_device_name(0),
                    uuid=str(torch.cuda.get_device_properties(0).uuid),runtime=backend.runtime)
                write_new(out/'hardware.json',record['hardware'])
            else:
                # Reconstruction allocates/initializes parameters before loading
                # their saved values. Discard those random draws and any draws
                # made by feedback rendering or orchestration between rounds.
                backend.prefix.restore_rng(training_rng,torch,np)
            stage_out=out/f'reconstruction_{round_index}';stage_out.mkdir()
            torch.cuda.synchronize()
            torch.cuda.reset_peak_memory_stats()
            start=time.perf_counter()
            previous_checkpoint=optimize(backend,cfg,rows,'sr',priors,steps,stage_out,clock_offset=0,
                sampling_rng=sampling_rng)
            torch.cuda.synchronize()
            training_seconds=time.perf_counter()-start
            training_rng=backend.prefix.rng_state(torch,np)
            record['rounds'].append(dict(round=round_index,checkpoint=previous_checkpoint,
                teacher_receipt=identity(teacher/'receipt.json'),teacher_seconds=teacher_seconds,
                teacher_timing_scope='subprocess wall time',seconds=training_seconds,training_seconds=training_seconds,
                training_timing_scope='optimization and checkpoint save; CUDA synchronized at both boundaries',
                peak_cuda_allocated_bytes=torch.cuda.max_memory_allocated(),
                peak_cuda_reserved_bytes=torch.cuda.max_memory_reserved(),
                training_rng_start='new SR seed after backend setup' if round_index==0 else 'previous round training-end state restored after backend reconstruction',
                LR_schedule='local 1..5000 each round; Adam preserved across rounds'))
            if round_index<3:
                rendered=render_training(backend,stage_out/'feedback')
                feedback=stage_out/'feedback_paths.json';write_new(feedback,rendered)
            elif not a.wiring_fixture_steps:
                evaluate(backend,previous_checkpoint,out/'evaluation')
            del backend;gc.collect();torch.cuda.empty_cache()
        write_new(out/'complete.json',dict(record,status='wiring_fixture_completed' if a.wiring_fixture_steps else 'completed_with_evaluation'))
    except BaseException:
        write_new(out/'failure.json',dict(record,status='failed',error=traceback.format_exc()))
        raise

if __name__=='__main__':main()
